// Build step for the static site.
//  1. Reads SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY from the environment (Vercel) or .env (local).
//  2. Refuses to build if a secret/service-role key was supplied by mistake.
//  3. Writes js/config.js and copies the public site into dist/ (what Vercel serves).
// Only public files are copied, so docs/, scripts/, supabase/ and .env never get deployed.

import { existsSync, readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync, statSync } from 'node:fs';
import { join, extname, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

// Minimal .env loader for local builds (Vercel injects real env vars).
const envFile = join(root, '.env');
if (existsSync(envFile)) {
  for (const line of readFileSync(envFile, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}

const url = process.env.SUPABASE_URL;
const key = process.env.SUPABASE_PUBLISHABLE_KEY || process.env.SUPABASE_ANON_KEY;

function fail(msg) {
  console.error(`\n✖ Build failed: ${msg}\n`);
  process.exit(1);
}

if (!url || !key) fail('SUPABASE_URL and SUPABASE_PUBLISHABLE_KEY must be set (see .env.example).');
if (!/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)\/?$/.test(url) && !url.startsWith('http://127.0.0.1')) {
  fail(`SUPABASE_URL does not look like a Supabase project URL: ${url}`);
}

// Guard against shipping a privileged key to the browser.
function isPrivilegedKey(k) {
  if (k.startsWith('sb_secret_')) return true;
  const parts = k.split('.');
  if (parts.length === 3) {
    try {
      const payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8'));
      return payload.role === 'service_role';
    } catch { /* not a JWT */ }
  }
  return false;
}
if (isPrivilegedKey(key)) {
  fail('SUPABASE_PUBLISHABLE_KEY is a SECRET / service_role key. Use the publishable (or anon) key instead.');
}

const configJs = `// Generated by scripts/build.mjs — do not edit or commit.
// These values are public by design; Row Level Security protects the data.
export const SUPABASE_URL = ${JSON.stringify(url.replace(/\/$/, ''))};
export const SUPABASE_PUBLISHABLE_KEY = ${JSON.stringify(key)};
`;
writeFileSync(join(root, 'js', 'config.js'), configJs);

// Copy public assets into dist/.
const PUBLIC_EXT = new Set(['.html', '.css', '.png', '.jpg', '.jpeg', '.gif', '.svg', '.webp', '.ico', '.pdf']);
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist);
for (const name of readdirSync(root)) {
  const full = join(root, name);
  if (statSync(full).isFile() && PUBLIC_EXT.has(extname(name).toLowerCase())) {
    cpSync(full, join(dist, name));
  }
}
cpSync(join(root, 'js'), join(dist, 'js'), { recursive: true });

console.log(`✔ Built dist/ for ${url}`);
